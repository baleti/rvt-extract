"""parse_joined -> build_payload -> page_stream of a lifted .rfa partition is byte-identical when the PT.K markers
come from the file's own payload (what RFA._partition_markers does). With the default markers it is NOT: that is
how a writer that re-serialises a partition must be driven. Opt-in: RVTX_SAMPLE_RFA=<lifted 2020-2023 .rfa>, W via RVTX_SAMPLE_W (default 4)."""
import os, struct, sys, unittest
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
S = os.environ.get('RVTX_SAMPLE_RFA', '')


@unittest.skipUnless(os.path.exists(S), 'needs RVTX_SAMPLE_RFA')
class PartitionFixpoint(unittest.TestCase):
    def test_roundtrip_with_own_markers(self):
        import rvtx, olefile, rvt2text as T
        from rvtx import partition as PT
        sys.path.insert(0, os.path.expanduser('~/rvt-research/write-lab'))
        import rvtw
        W = int(os.environ.get('RVTX_SAMPLE_W', '4'))
        o = olefile.OleFileIO(S)
        pn = sorted((y for y in ['/'.join(e) for e in o.listdir(streams=True)] if y.startswith('Partitions/')), key=lambda s: int(s.split('/')[1]))[0]
        raw = o.openstream(pn).read(); pay = rvtw.Stream(raw).payload
        old = dict(PT.K)
        try:
            PT.K['version'] = struct.unpack_from('<Q', pay, 0)[0]; PT.K['hdrtag'] = pay[8:10]; PT.K['m1'] = pay[18:20]
            t = pay.rfind('Data generated by Autodesk'.encode('utf-16le'))
            if t > 0:
                PT.K['blobm'] = pay[t - 74:t - 72]
                k = pay.rfind(PT.K['m1'] + b'\0' * 16, 0, t)
                if k >= 6: PT.K['m0'] = pay[k - 6:k - 4]
                PT.K['cdtag'] = pay[t + 68 + 0:t + 68] or PT.K['cdtag']
            docs = PT.parse_joined(T.joined(raw), W)
            a = T.strip_pages(raw); b = T.strip_pages(PT.page_stream(PT.build_payload(docs, W)))
            diff = [i for i in range(min(len(a), len(b))) if a[i] != b[i]]
            self.assertEqual(len(a), len(b))
            # only the 2-byte content-document tag at the tail is allowed to differ (set per file by the lift via SS.TAGS)
            self.assertLessEqual(len(diff), 4, diff[:10])
        finally:
            PT.K.clear(); PT.K.update(old)


if __name__ == '__main__':
    unittest.main()
