import os, unittest
from rvtx import rfa, elemtable


class FakeBuilder:
    """nested_docs from a parent -> descendants table (flattened, like Builder.nested_docs)"""
    nested_depth = rfa.Builder.nested_depth

    def __init__(self, tree):
        self.tree = tree

    def nested_docs(self, k, seen=None):
        out = []
        for c in self.tree.get(k, []):
            out.append((c, 'g%d' % c)); out += self.nested_docs(c)
        return out


class NestedDepthTests(unittest.TestCase):
    def test_depths(self):
        b = FakeBuilder({0: [1, 2], 1: [3], 3: [4]})
        self.assertEqual(b.nested_depth(4), 0)
        self.assertEqual(b.nested_depth(3), 1)
        self.assertEqual(b.nested_depth(1), 2)
        self.assertEqual(b.nested_depth(2), 0)
        self.assertEqual(b.nested_depth(0), 3)      # 0 -> 1 -> 3 -> 4

    def test_flat_has_depth_zero(self):
        self.assertEqual(FakeBuilder({}).nested_depth(0), 0)


class ElemTableDatesTests(unittest.TestCase):
    def rows(self, mode):
        os.environ['RVTX_ETDATES'] = mode
        try: t = elemtable.build4([5, 9], {9}, {9: b'\x01\x02\x03\x04' + b'\xcf\x03\0\0' + b'\xef\x03\0\0'}, 77)
        finally: os.environ.pop('RVTX_ETDATES', None)
        return t[6:6 + 56]

    def test_real_mode_has_no_project_dates(self):
        r = self.rows('real')[28:56]      # row of element 9
        self.assertEqual(r[8:16], b'\0' * 8)      # a = b = 0, so Revit does not drop the row as a 'missing element'
        self.assertEqual(r[16:20], b'\xff' * 4)

    def test_old_mode_keeps_project_dates(self):
        self.assertEqual(self.rows('old')[28:56][8:12], b'\xcf\x03\0\0')


if __name__ == '__main__':
    unittest.main()


class DocBoundaryTests(unittest.TestCase):
    """old formats (4-byte ids): Revit ends each document with a tail block naming the next one (synthetic documents, no Autodesk data)"""
    def docs(self):
        def d(base, n): return {'H': [(base + i, b'\x01\x00' + bytes(8)) for i in range(n)] + [(0xFFFFFFFF, b'')], 'R': [(base + i, b'\x02\x00' + bytes(8), 0) for i in range(n)] + [(0xFFFFFFFF, b'', 0)], 'Z': [(base + i, b'\x03\x00') for i in range(n)] + [(0xFFFFFFFF, b'')]}
        return [d(10, 3), d(100, 2)]

    def test_block_between_documents(self):
        from rvtx import partition as PT
        g = bytes(range(16)); t = 'Data generated by Autodesk® Revit®'.encode('utf-16le')
        with_blk = PT.build_payload(self.docs(), 4, doc_guids={1: (2, g)})
        plain = PT.build_payload(self.docs(), 4)
        self.assertEqual(with_blk.count(t), 2)
        self.assertEqual(plain.count(t), 1)
        k = with_blk.find(t)
        tail = with_blk[k + len(t):k + len(t) + 2 + 4 + 2 + 4 + 16]
        self.assertEqual(tail[2:6], b'\xff' * 4)
        self.assertEqual(tail[8:12], (2).to_bytes(4, 'little'))
        self.assertEqual(tail[12:28], g)

    def test_old_layout_has_no_text_block(self):
        from rvtx import partition as PT
        g = bytes(range(16)); t = 'Data generated by Autodesk® Revit®'.encode('utf-16le')
        p = PT.build_payload(self.docs(), 4, doc_guids={1: (2, g)}, nf_seq=(400, 4), hs_adj=-4, plain_tail=True)
        self.assertEqual(p.count(t), 0)
        self.assertIn(g, p)
