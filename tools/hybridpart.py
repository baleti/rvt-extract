"""hybridpart.py GT.rfa OURS.rfa OUTDIR : Revit's rfa with its partition rebuilt (our framing) from: P0 its own records, P1 R from ours, P2 H from ours, P3 Z from ours (same id sets required)"""
import sys, os, struct, olefile
sys.path[:0] = [os.path.join(os.path.dirname(os.path.realpath(__file__)), '..'), os.path.expanduser('~/rvt-research'), os.path.expanduser('~/rvt-research/write-lab')]
import rvt2text as T, rvtw
from rvtx import cfbw, partition as PT
gt, ours, od = sys.argv[1:4]
og, oo = olefile.OleFileIO(gt), olefile.OleFileIO(ours)
def pn(o): return '/'.join(next(e for e in o.listdir(streams=True) if e[0] == 'Partitions'))
G = PT.parse_joined(T.joined(og.openstream(pn(og)).read()), 8); O = PT.parse_joined(T.joined(oo.openstream(pn(oo)).read()), 8)
P0 = rvtw.Stream(og.openstream(pn(og)).read()).payload
PT.K.update(version=struct.unpack_from('<Q', P0, 0)[0], hdrtag=P0[8:10], m1=P0[18:20])
t = P0.rfind('Data generated by Autodesk'.encode('utf-16le')); PT.K['blobm'] = P0[t-4-4-64-2:t-4-4-64]
k = P0.rfind(PT.K['m1'] + b'\0' * 16, 0, t); PT.K['m0'] = P0[k-6:k-4]; PT.K['cdtag'] = P0[t + 68:t + 70]; blob = P0[t-4-64:t-4]
ne = struct.unpack_from('<I', P0, 14)[0]
base = {n: og.openstream(n).read() for n in ['/'.join(e) for e in og.listdir(streams=True)]}
NEG = (1 << 64) - 1
def variant(tag, regs):
    docs = []
    for kd, d in enumerate(G):
        nd = {r: list(d[r]) for r in 'HRZ'}
        if kd == 0:
            for r in regs:
                od_ = {x[0]: x for x in O[0][r]}
                nd[r] = [od_.get(x[0], x) if x[0] != NEG else x for x in d[r]]
        docs.append(nd)
    pay = PT.build_payload(docs, 8, element_count=ne, blob=blob)
    st = dict(base); st[pn(og)] = PT.page_stream(pay)
    d = os.path.join(od, tag); os.makedirs(d, exist_ok=True); open(os.path.join(d, 'h.rfa'), 'wb').write(cfbw.write_rfa(st, pn(og)))
variant('P0', ''); variant('P1', 'R'); variant('P2', 'H'); variant('P3', 'Z')
