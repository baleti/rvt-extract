"""hybrid2020.py SAMPLE.rfa OUTDIR : bisect helper. A = real streams through our container writer (partition renamed Partitions/0); B = A with the partition payload re-paged by rvtx.partition.page_stream"""
import sys, os, olefile
sys.path[:0] = [os.path.join(os.path.dirname(os.path.realpath(__file__)), '..'), os.path.expanduser('~/rvt-research'), os.path.expanduser('~/rvt-research/write-lab')]
from rvtx import cfbw, partition as PT
import rvtw
src, od = sys.argv[1], sys.argv[2]; os.makedirs(od + '/A', exist_ok=True); os.makedirs(od + '/B', exist_ok=True); os.makedirs(od + '/D', exist_ok=True)
o = olefile.OleFileIO(src); st = {}
for e in o.listdir(streams=True):
    n = '/'.join(e); d = o.openstream(n).read()
    st['Partitions/0' if n.startswith('Partitions/') else n] = d
open(od + '/A/a.rfa', 'wb').write(cfbw.write_rfa(st))
pay = rvtw.Stream(st['Partitions/0']).payload; pn = [e for e in o.listdir(streams=True) if e[0] == 'Partitions'][0]; pn = '/'.join(pn)
st3 = {k: v for k, v in st.items() if k != 'Partitions/0'}; st3[pn] = st['Partitions/0']
open(od + '/D/d.rfa', 'wb').write(cfbw.write_rfa(st3, pn))
print('payload', len(pay), 'orig stored', len(st['Partitions/0']))
# strip zero padding of the last page: the payload ends with the marker text + tag + zeros; keep exact tail by trimming trailing zeros beyond the known end
t = pay.rfind('Data generated by Autodesk'.encode('utf-16le')); end = t + len('Data generated by Autodesk® Revit®'.encode('utf-16le')) + 14
st2 = dict(st); st2['Partitions/0'] = PT.page_stream(pay[:end] + b'\0' * 0)
print('end', end, 'rest nonzero', any(pay[end:]), 'repaged', len(st2['Partitions/0']))
open(od + '/B/b.rfa', 'wb').write(cfbw.write_rfa(st2))

# E: real streams, real partition name, partition rebuilt by our writer (parse_joined -> build_payload with our deflate -> page_stream)
import struct
from rvtx import partition as PT2
os.makedirs(od + '/E', exist_ok=True)
import rvt2text as T
W = 4
j = T.joined(o.openstream(pn).read()); docs = PT2.parse_joined(j, W)
P0 = rvtw.Stream(st3[pn]).payload
PT2.K.update(version=struct.unpack_from('<Q', P0, 0)[0], hdrtag=P0[8:10], m1=P0[18:20])
t = P0.rfind('Data generated by Autodesk'.encode('utf-16le')); PT2.K['blobm'] = P0[t-4-4-64-2:t-4-4-64]
k = P0.rfind(PT2.K['m1'] + b'\0' * 16, 0, t); PT2.K['m0'] = P0[k-6:k-4]
PT2.K['cdtag'] = P0[t + 68:t + 70]
blob = P0[t-4-64:t-4]
pay2 = PT2.build_payload(docs, W, element_count=struct.unpack_from('<I', P0, 14)[0], blob=blob)
st4 = dict(st3); st4[pn] = PT2.page_stream(pay2)
open(od + '/E/e.rfa', 'wb').write(cfbw.write_rfa(st4, pn)); print('E partition', len(P0), len(pay2))
